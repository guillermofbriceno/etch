// Builds src/lib/emojiData.ts from Unicode's emoji-test.txt and CLDR's English annotations.
// Usage: pnpm emoji:data <emoji-test.txt> <cldr/common>; inside `nix develop` both default to the pinned nixpkgs.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const emojiTest = process.argv[2] ?? process.env.ETCH_EMOJI_TEST;
const cldr = process.argv[3] ?? process.env.ETCH_CLDR_ANNOTATIONS;
if (!emojiTest || !cldr) {
    console.error('Usage: pnpm emoji:data <emoji-test.txt> <cldr/common directory>');
    console.error('emoji-test.txt is at unicode.org/Public/emoji/<version>/; cldr/common is from the CLDR release.');
    process.exit(1);
}

const TAB_ICONS = {
    'Smileys & Emotion': '😀',
    'People & Body': '👋',
    'Animals & Nature': '🐻',
    'Food & Drink': '🍔',
    'Travel & Places': '✈️',
    'Activities': '⚽',
    'Objects': '💡',
    'Symbols': '🔣',
    'Flags': '🏁',
};

const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;
const stripVs = (s) => s.replaceAll('️', '');
const decode = (s) => s
    .replaceAll('&quot;', '"').replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&');

const keywords = new Map();
for (const file of ['annotations/en.xml', 'annotationsDerived/en.xml']) {
    const xml = readFileSync(join(cldr, file), 'utf8');
    for (const [, cp, text] of xml.matchAll(/<annotation cp="([^"]+)">([^<]*)<\/annotation>/g)) {
        keywords.set(stripVs(decode(cp)), decode(text).split('|').map((k) => k.trim().toLowerCase()));
    }
}

const text = readFileSync(emojiTest, 'utf8');
const version = text.match(/^# Version: (\S+)/m)?.[1];
const groups = [];
for (const line of text.split('\n')) {
    const group = line.match(/^# group: (.+)$/);
    if (group) {
        groups.push({ name: group[1], emojis: [] });
        continue;
    }
    const entry = line.match(/; fully-qualified\s+# (\S+) E(\S+) (.+)$/);
    if (!entry || SKIN_TONE.test(entry[1])) continue;
    const [, emoji, emojiVersion, name] = entry;
    const nameWords = new Set(name.toLowerCase().split(/\s+/));
    const extra = new Set();
    for (const k of keywords.get(stripVs(emoji)) ?? []) {
        for (const w of k.split(/\s+/)) if (!nameWords.has(w)) extra.add(w);
    }
    groups.at(-1).emojis.push([emoji, name, [...extra].join(' '), Number(emojiVersion)]);
}

const shown = groups.filter((g) => g.name !== 'Component');
for (const g of shown) {
    if (!TAB_ICONS[g.name]) throw new Error(`No tab icon for emoji group "${g.name}"`);
}

const q = (s) => JSON.stringify(s);
const body = shown.map((g) => [
    `    { name: ${q(g.name)}, icon: ${q(TAB_ICONS[g.name])}, emojis: [`,
    ...g.emojis.map(([e, n, k, v]) => `        [${q(e)}, ${q(n)}, ${q(k)}, ${v}],`),
    '    ] },',
].join('\n')).join('\n');

const out = `// Generated by scripts/generate-emoji-data.js from Unicode emoji ${version}; do not edit.
import type { EmojiGroupData } from './emoji';

export const EMOJI_DATA: EmojiGroupData[] = [
${body}
];
`;
writeFileSync(new URL('../src/lib/emojiData.ts', import.meta.url), out);
console.log(`Wrote ${shown.reduce((n, g) => n + g.emojis.length, 0)} emoji in ${shown.length} groups (Unicode ${version}).`);
